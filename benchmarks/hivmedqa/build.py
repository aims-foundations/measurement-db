"""Tabulate original HIVMedQA runs and their recorded clinical judge ratings."""

import json
import re
import sys
import tarfile
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
from measurement_db.build_base import BenchmarkBuild, Judge


class HIVMedQA(BenchmarkBuild):
    def download(self):
        return self.fetch_sources("author", "historical", "release", "questions")

    def build_tables(self) -> dict[str, pd.DataFrame]:
        parameters, paths = self.build_parameters, self.build_parameters["paths"]
        keys = ["configuration", "category_id", "iteration_number", "question_index"]

        # 1. Read native JSON lists and CSV cells; retain every original source record.
        with tarfile.open(self.raw_dir / paths["archive"]) as archive:
            root = paths["root"] + "/"
            members = [member for member in archive if member.isfile()
                and member.name.startswith((root + paths["answers"], root + paths["controls"])) and member.name.endswith("_HIV_EQ.json")]
            data = pd.DataFrame({"source_file":[member.name.removeprefix(root) for member in members],
                "source_record":[json.load(archive.extractfile(member)) for member in members]})
        data = data.explode("source_record", ignore_index=True).dropna(subset="source_record")
        data["question_index"] = data.groupby("source_file", sort=False).cumcount().astype(str)
        data["role"] = data.source_file.str.removeprefix(paths["answers"]).str.split("/").str[0]
        data["configuration"] = data.source_file.str.split("/").str[-2]
        controls = data.source_file.str.startswith(paths["controls"])
        data.loc[controls, "role"] = data.loc[controls, "source_file"].str.removeprefix(paths["controls"]).str.split("/").str[0]
        data.loc[controls, "configuration"] = parameters["association"]["control_configuration"]
        data[["category_id", "iteration_number"]] = data.source_file.str.extract(r"_answers_category_(\d+)\.(\d+)_HIV_EQ\.json$")
        if data[keys].isna().any().any():
            raise ValueError("A native result filename lacks its task/iteration identity")
        historical = pd.read_csv(self.raw_dir / paths["historical"], dtype=str, keep_default_na=False)
        historical["historical_record"] = historical.to_dict("records")
        historical["historical_row"] = historical.index
        historical["configuration"] = historical.subfolder

        # 2. Recover Gemini's empty current answer lists from the historical native table.
        answers = data.loc[data.role.eq("raw"), keys + ["source_file", "source_record"]].copy()
        answers["question"] = answers.source_record.str["question"]
        answers["answer"] = answers.source_record.str["answer"]
        answers["gold"] = answers.source_record.str["true_answer"]
        answers["retrieval"] = answers.source_record.map(lambda record: json.dumps(record.get("rag_sources", []), ensure_ascii=False, sort_keys=True))
        answers["source_kind"] = "native_json"
        recovered = historical.merge(answers[keys], on=keys, how="left", indicator=True, validate="one_to_one")
        recovered = recovered.loc[recovered._merge.eq("left_only")].copy()
        if set(recovered.configuration) != {parameters["association"]["historical_fallback"]}:
            raise ValueError("Unexpected missing native answers; historical recovery requires review")
        recovered["source_file"] = paths["historical"]
        recovered["source_record"] = recovered.historical_record
        recovered["source_kind"] = "historical_csv"
        recovered["answer"], recovered["gold"], recovered["retrieval"] = recovered.model_answer, recovered.gold_answer, "[]"
        answers = pd.concat([answers, recovered[answers.columns]], ignore_index=True)
        answers["input_text"], answers["task_role"] = answers.question, "question_answering"

        # The reference-paraphrasing controls are generated by GPT-4o with the answer supplied.
        controls = data.loc[data.role.eq("rephrased_true_answers"), keys + ["source_file", "source_record"]].reset_index(drop=True)
        controls = controls.join(pd.json_normalize(controls.source_record.str["response"].str.extract(r"(\{.*\})", flags=re.DOTALL, expand=False).map(json.loads)).rename(
            columns={"true_answer":"gold", "true_answer_rephrased":"answer"}))
        generation_prompts = data.loc[data.role.eq("prompted_to_rephrase"), keys + ["source_file", "source_record"]].rename(
            columns={"source_file":"generation_prompt_file", "source_record":"generation_prompt_record"})
        controls = controls.merge(generation_prompts, on=keys, how="left", validate="one_to_one")
        controls["input_text"] = controls.generation_prompt_record.str["prompt"]
        if controls.input_text.isna().any():
            raise ValueError("A reference-paraphrasing run lacks its recorded generation prompt")
        controls["retrieval"], controls["source_kind"], controls["task_role"] = "[]", "native_json", "reference_paraphrasing"
        answers = pd.concat([answers, controls], ignore_index=True)

        # 3. Attach the original release as source aliases, not additional agent attempts.
        release = pd.read_csv(self.raw_dir / paths["release"], dtype=str, keep_default_na=False)
        release["release_record"] = release.to_dict("records")
        release["question_match"] = release.question.str.replace(parameters["association"]["normalization"], "", regex=True)
        historical["release_model"] = historical.model.map(parameters["legacy_models"])
        controls["release_model"] = parameters["association"]["control"]
        lookup = pd.concat([historical, controls], ignore_index=True)[keys + ["question", "release_model"]]
        lookup["question_match"] = lookup.question.str.replace(parameters["association"]["normalization"], "", regex=True)
        aliases = release.merge(lookup, left_on=["model", "question_match", "iteration_number"],
            right_on=["release_model", "question_match", "iteration_number"], how="left", suffixes=("_release", ""), validate="many_to_one")
        if aliases.configuration.isna().any():
            raise ValueError("An original release observation lacks its historical source association")
        aliases = aliases.groupby(keys, sort=False).agg(release_aliases=("release_record", list)).reset_index()
        answers = answers.merge(aliases, on=keys, how="left", validate="one_to_one")
        answers["release_aliases"] = answers.release_aliases.map(lambda value: value if isinstance(value, list) else [])

        # 4. Join saved grading requests/replies, retaining requested but unfinished grading.
        data["protocol"] = data.role.map(parameters["role_protocols"])
        prompts = data.loc[data.role.str.startswith("prompted_") & data.protocol.notna(), keys + ["protocol", "source_file", "source_record"]].rename(
            columns={"source_file":"judge_prompt_file", "source_record":"judge_prompt_record"})
        replies = data.loc[data.role.str.startswith("results-"), keys + ["protocol", "source_file", "source_record"]].rename(
            columns={"source_file":"judge_reply_file", "source_record":"judge_reply_record"})
        evaluations = prompts.merge(replies, on=keys + ["protocol"], how="outer", validate="one_to_one")
        evaluations = evaluations.merge(answers, on=keys, how="left", validate="many_to_one")
        if evaluations.question.isna().any():
            raise ValueError("A grading record lacks its recorded model input")
        for column in ["judge_prompt_file", "judge_prompt_record", "judge_reply_file", "judge_reply_record"]:
            evaluations[column] = evaluations[column].where(evaluations[column].notna(), None)
        blocks = evaluations.judge_reply_record.str["response"].str.extract(r"(\{.*\})", flags=re.DOTALL, expand=False)
        decoded = blocks.map(lambda value: json.loads(value) if isinstance(value, str) else {})
        grades = pd.json_normalize(decoded).reindex(columns=parameters["dimensions"])
        evaluations = evaluations.reset_index(drop=True).join(grades)
        evaluations["reply_status"] = "available"
        evaluations.loc[blocks.isna().to_numpy(), "reply_status"] = "no_json_object"
        evaluations.loc[evaluations.judge_reply_record.isna(), "reply_status"] = "missing_judge_output"
        judgments = evaluations.melt(id_vars=[column for column in evaluations if column not in parameters["dimensions"]],
            value_vars=list(parameters["dimensions"]), var_name="source_field", value_name="native_grade")
        judgments["response"] = pd.to_numeric(judgments.native_grade, errors="coerce")
        if not judgments.loc[judgments.response.notna(), "response"].between(0, 5).all():
            raise ValueError("Native numeric judge grades must be finite and in [0,5]")
        judgments["grading_status"] = judgments.reply_status
        judgments.loc[judgments.response.isna() & judgments.reply_status.eq("available"), "grading_status"] = "missing_or_nonnumeric_grade"
        judgments["dimension"] = judgments.source_field.map(parameters["dimensions"])

        # 5. Define tasks by their actual inputs and grading protocol, including supplied controls.
        item_fields = ["input_text", "gold", "retrieval", "task_role", "protocol", "dimension"]
        items = judgments[item_fields + ["category_id", "question_index"]].drop_duplicates(item_fields).reset_index(drop=True)
        items["item_key"] = items.index.astype(str)
        items["raw_item_id"] = "category_" + items.category_id + ":question_" + items.question_index
        items["content"] = [json.dumps(dict(multimedia_elements=[dict(content_type="text/plain", text=row.input_text)]
            + ([dict(content_type="text/plain", text=parameters["presentation"]["retrieval"].format(references=row.retrieval))] if row.retrieval != "[]" else [])), ensure_ascii=False)
            for row in items.itertuples()]
        items["features"] = [dict(task_role=row.task_role, input_scope=parameters["presentation"][row.task_role]) for row in items.itertuples()]
        items["grading_criterion"] = [dict(reference_answer=row.gold if row.protocol != "reference_free" else None,
            rule=self.grading["rule"] + "\nClinical dimension: " + row.dimension + "\nGrading protocol: " + row.protocol) for row in items.itertuples()]
        items["verifier"] = [Judge(judge=self.grading["verifiers"][row.protocol]["judge"], judged_by="llm",
            spec=json.dumps(self.grading["verifiers"][row.protocol], sort_keys=True)) for row in items.itertuples()]
        judgments = judgments.merge(items[item_fields + ["item_key"]], on=item_fields, how="left", validate="many_to_one")
        subjects = answers[["configuration", "task_role"]].drop_duplicates().rename(columns={"configuration":"subject_key"})
        subjects["raw_label"] = subjects.subject_key.map(parameters["model_labels"])
        if subjects.raw_label.isna().any():
            raise ValueError("A recorded configuration lacks its source model declaration")
        subjects["features"] = [dict(source_configuration=row.subject_key, task_role=row.task_role, **parameters["subject_features"]) for row in subjects.itertuples()]

        # 6. Preserve native trial numbers, full judge text and the original-release aliases.
        judgments["subject_key"] = judgments.configuration
        judgments["trial"] = pd.to_numeric(judgments.iteration_number, errors="raise")
        judgments["response_key"] = judgments[keys + ["protocol", "source_field"]].agg(":".join, axis=1)
        trace_fields = keys + ["source_kind", "source_file", "source_record", "task_role", "generation_prompt_file", "generation_prompt_record", "protocol", "source_field", "grading_status",
            "judge_prompt_file", "judge_prompt_record", "judge_reply_file", "judge_reply_record", "release_aliases"]
        traces = judgments[["response_key"] + trace_fields].astype(object)
        traces = traces.where(traces.notna(), None)
        traces["trace"] = [json.dumps(record, ensure_ascii=False, allow_nan=False) for record in traces[trace_fields].to_dict("records")]
        return {"subjects": subjects[["subject_key", "raw_label", "features"]], "items": items[["item_key", "raw_item_id", "content", "features", "grading_criterion", "verifier"]],
            "responses": judgments[["response_key", "subject_key", "item_key", "trial", "response"]],
            "traces": traces[["response_key", "trace"]]}


if __name__ == "__main__":
    HIVMedQA(__file__).main()
